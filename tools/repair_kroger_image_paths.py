#!/usr/bin/env python3
import json
import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple


# Ensure project root is on sys.path so we can import filename_utils when
# running as: python tools/repair_kroger_image_paths.py
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from filename_utils import sanitize_component


def legacy_type_token(ad_type: str) -> str:
    t = (ad_type or "").lower()
    if "skyscraper" in t:
        return "skyscraper"
    if "carousel" in t:
        return "carousel"
    return "toa"


def parse_png_key(client: str, png_path: Path) -> Optional[Tuple[str, str, str, Optional[str]]]:
    """Return (client_clean, ad_type_clean, search_term_clean, advertiser_clean|None) for a PNG.

    Filenames are generated by filename_utils.generate_ad_filename, so we
    can parse the core components from the stem.
    """
    name = png_path.stem
    parts = name.split("__")
    if len(parts) < 5:
        return None

    # With advertiser: retailer__advertisers__ad_type__client__search_term__...
    # Without advertiser: retailer__ad_type__client__search_term__...
    if len(parts) == 5:
        _, ad_type, client_raw, search_term_raw, _ = parts
        advertiser_raw = None
    else:
        # Allow extra segments beyond the first 6; keep the expected ones.
        _, advertiser_raw, ad_type, client_raw, search_term_raw, *_ = parts

    client_clean = sanitize_component(client or client_raw, max_length=30)
    ad_type_clean = sanitize_component(ad_type, max_length=30)
    search_term_clean = sanitize_component(search_term_raw, max_length=50)

    advertiser_clean: Optional[str] = None
    if advertiser_raw:
        advertiser_clean = advertiser_raw

    return (client_clean, ad_type_clean, search_term_clean, advertiser_clean)


def build_png_index(client_dir: Path, client_slug: str) -> Dict[Tuple[str, str, str, Optional[str]], str]:
    """Index existing PNGs under a Kroger client by logical key.

    The value is a relative path from client_dir (e.g. "TOA/...png").
    If multiple PNGs share the same key, the most recent one wins.
    """
    index: Dict[Tuple[str, str, str, Optional[str]], str] = {}

    if not client_dir.is_dir():
        return index

    png_files: List[Path] = []
    for sub in ("TOA", "Skyscraper", "Carousel"):
        root = client_dir / sub
        if root.is_dir():
            png_files.extend(root.rglob("*.png"))

    # Sort by mtime so the latest file for a key wins
    png_files.sort(key=lambda p: p.stat().st_mtime)

    for p in png_files:
        key = parse_png_key(client_slug, p)
        if not key:
            continue
        rel = p.relative_to(client_dir).as_posix()
        index[key] = rel

    return index


def advertiser_key_from_ad(ad: Dict) -> Optional[str]:
    adv = ad.get("advertisers")
    if not adv:
        single = ad.get("advertiser")
        adv = [single] if single else None
    if not adv:
        return None
    cleaned: List[str] = []
    for a in adv:
        if not a:
            continue
        cleaned.append(sanitize_component(a, max_length=30, preserve_ampersand=True))
    if not cleaned:
        return None
    return "+".join(cleaned)


def ad_key_for_json_ad(data: Dict, container_meta: Dict, ad: Dict, client_slug: str) -> Tuple[str, str, str, Optional[str]]:
    client = data.get("client") or client_slug
    client_clean = sanitize_component(client, max_length=30)

    ad_type_raw = ad.get("type", "TOA")
    ad_type_token = legacy_type_token(ad_type_raw)
    ad_type_clean = sanitize_component(ad_type_token, max_length=30)

    # Match how screenshot_ad_image derives search_term
    search_term = container_meta.get("search_term") or container_meta.get("keyword") or data.get("search_term") or data.get("keyword") or "unknown"
    search_term_clean = sanitize_component(search_term, max_length=50)

    advertiser_clean = advertiser_key_from_ad(ad)

    return (client_clean, ad_type_clean, search_term_clean, advertiser_clean)


def repair_json(json_path: Path, client_slug: str, png_index: Dict[Tuple[str, str, str, Optional[str]], str]) -> int:
    """Repair a single run_results JSON file.

    Returns number of ads updated.
    """
    try:
        data = json.loads(json_path.read_text(encoding="utf-8"))
    except Exception:
        return 0

    updated = 0

    def try_update_ad(container_meta: Dict, ad: Dict) -> None:
        nonlocal updated
        if ad.get("image_path"):
            return
        if not ad.get("image_url"):
            return

        key = ad_key_for_json_ad(data, container_meta, ad, client_slug)
        rel = png_index.get(key)
        if not rel:
            return

        ad["image_path"] = rel
        updated += 1

    # Aggregated shape: results[].ads[]
    results = data.get("results") or []
    for result in results:
        meta = {
            "search_term": result.get("search_term"),
            "keyword": result.get("keyword"),
        }
        for ad in result.get("ads", []):
            try_update_ad(meta, ad)

    # Per-run shape: top-level ads[]
    top_ads = data.get("ads")
    if isinstance(top_ads, list):
        meta = {
            "search_term": data.get("search_term"),
            "keyword": data.get("keyword"),
        }
        for ad in top_ads:
            try_update_ad(meta, ad)

    if updated:
        json_path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")

    return updated


def main() -> None:
    project_root = Path(__file__).resolve().parent.parent
    kroger_root = project_root / "output" / "kroger"

    if not kroger_root.is_dir():
        print(f"No Kroger output directory found at {kroger_root}")
        return

    total_updated = 0

    for client_dir in sorted(p for p in kroger_root.iterdir() if p.is_dir()):
        client_slug = client_dir.name
        runs_dir = client_dir / "runs"
        if not runs_dir.is_dir():
            continue

        print(f"\n=== Repairing client: {client_slug} ===")
        png_index = build_png_index(client_dir, client_slug)
        if not png_index:
            print("  No PNGs found; skipping")
            continue

        client_updated = 0
        for json_path in sorted(runs_dir.glob("run_results_*.json")):
            updated = repair_json(json_path, client_slug, png_index)
            if updated:
                print(f"  {json_path.name}: fixed {updated} ads")
                client_updated += updated

        print(f"  Total fixed for {client_slug}: {client_updated}")
        total_updated += client_updated

    print(f"\nOverall repaired ads: {total_updated}")


if __name__ == "__main__":
    main()
