def main():
    import argparse
    ap = argparse.ArgumentParser(description="Compose a retailer adapter from capability profile and/or hint pack")
    ap.add_argument("--profile", help="Path to capability profile JSON (optional if hint-pack provided)")
    ap.add_argument("--hint-pack", help="Path to Ad Type Hint Pack YAML (takes priority)")
    ap.add_argument("--slug", help="Retailer slug (overrides auto-detection)")
    args = ap.parse_args()
    
    if not args.profile and not args.hint_pack:
        print("❌ Must provide --profile and/or --hint-pack")
        sys.exit(1)
    
    # Load hint pack (priority)
    hint_pack = None
    if args.hint_pack:
        hint_path = Path(args.hint_pack)
        if not hint_path.exists():
            print(f"❌ Hint pack not found: {hint_path}")
            sys.exit(1)
        hint_pack = load_hint_pack(hint_path)
        print(f"📦 Loaded hint pack: {hint_path}")
    
    # Load profile (optional if hint pack provided)
    caps = {}
    if args.profile:
        profile_path = Path(args.profile)
        if not profile_path.exists():
            print(f"❌ Profile not found: {profile_path}")
            sys.exit(1)
        caps = json.loads(profile_path.read_text())
        print(f"📊 Loaded profile: {profile_path}")
    
    # Determine slug
    if args.slug:
        slug = args.slug
    elif hint_pack:
        slug = hint_pack.get("retailer", "unknown")
    elif caps:
        slug = caps.get("retailer_hint", "unknown").replace("www.", "").split(".")[0]
    else:
        print("❌ Could not determine retailer slug")
        sys.exit(1)
    
    print(f"\n🏗️  Composing retailer adapter for: {slug}")
    if hint_pack:
        print(f"   Source: Hint Pack (priority)")
    if caps:
        print(f"   Augmented by: Profiler")
    print()
    
    # Analyze and recommend (hint pack takes priority)
    pick = recommend(caps, hint_pack)
    
    print("📋 Recommendations:")
    print(f"   Use Kroger-like profile: {pick['use_kroger_profile']}")
    print(f"   Use Walmart-like navigation: {pick['use_walmart_nav']}")
    print(f"   Use Instacart-like scroller: {pick['use_instacart_scroller']}")
    print(f"   Ad types: {', '.join(pick['adtypes']) if pick['adtypes'] else 'None detected'}")
    print()
    
    # Generate files
    print("📝 Generating files...")
    write_adapter(slug, caps, pick)
    write_search_script(slug, caps, pick)
    write_init(slug)
    update_taxonomy(slug, pick["adtypes"])
    update_keyword_input(slug)
    create_setup_script(slug, caps)
    
    print()
    print("✅ Composition complete!")
    print()
    print("📌 Next steps:")
    print(f"   1. Run: ./scripts/setup_{slug}_profile.sh")
    print(f"   2. Add {slug.upper()}_PROFILE_DIR to config/launcher.env")
    print(f"   3. Update {slug}_search_and_capture.py with actual ad selectors")
    print(f"   4. Test: python3 {slug}_search_and_capture.py 'test' --output-dir output/{slug}/test")
    print(f"   5. Test in GUI: python3 keyword_input.py")
    print()

if __name__ == "__main__":
    main()
