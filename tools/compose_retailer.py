#!/usr/bin/env python3
"""
Retailer Composer

Reads a capability profile JSON and/or Ad Type Hint Pack YAML and scaffolds 
a production-ready retailer adapter. Enforces canonical schema, brand lexicon, 
and path taxonomy.

Hint Pack takes priority over profiler heuristics.
"""
import json, os, sys, shutil, yaml
from pathlib import Path
from datetime import datetime

PROJECT = Path(__file__).resolve().parents[1]

RULES = {
    "kroger_like": lambda caps: caps["requires_auth"] or caps["persistent_profile_required"],
    "walmart_like": lambda caps: caps["anti_bot_vendor"] in ("perimeterx","akamai","cloudflare") or not caps["headless_allowed"],
    "instacart_like": lambda caps: caps["has_lazy_loading"] or caps["hashed_class_density"] in ("high","medium"),
}

ADTYPE_MAP = {
    "CuratedCarousel": "Carousel",
    "TOA": "TOA",
    "Skyscraper": "Skyscraper",
    "SBA": "SBA",
    "SBV": "SBV",
    "Tile_Takeover": "Tile_Takeover",
}

def load_hint_pack(hint_path: Path) -> dict:
    """Load Ad Type Hint Pack YAML"""
    if not hint_path.exists():
        return None
    return yaml.safe_load(hint_path.read_text())

def recommend(caps: dict, hint_pack: dict = None) -> dict:
    """Analyze capabilities and recommend code patterns
    
    Hint pack takes priority over profiler heuristics.
    """
    # If hint pack provided, use it as source of truth
    if hint_pack:
        pick = {
            "use_kroger_profile": hint_pack.get("requires_auth", False),
            "use_walmart_nav": hint_pack.get("anti_bot_hint", {}).get("vendor") in ("perimeterx", "akamai", "cloudflare"),
            "use_instacart_scroller": False,  # Can be inferred from notes
            "adtypes": [ad["canonical"] for ad in hint_pack.get("ad_types", [])],
            "hint_pack": hint_pack,  # Pass through for detailed extraction
        }
        return pick
    
    # Fallback to profiler heuristics
    pick = {
        "use_kroger_profile": RULES["kroger_like"](caps),
        "use_walmart_nav": RULES["walmart_like"](caps),
        "use_instacart_scroller": RULES["instacart_like"](caps),
        "adtypes": [],
        "hint_pack": None,
    }
    hints = caps.get("ad_hints", {})
    if hints.get("curated_carousel_like"): pick["adtypes"].append("CuratedCarousel")
    if hints.get("toa_like"): pick["adtypes"].append("TOA")
    if hints.get("skyscraper_like"): pick["adtypes"].append("Skyscraper")
    if hints.get("sba_like"): pick["adtypes"].append("SBA")
    if hints.get("video_in_grid_like"): pick["adtypes"].append("SBV")
    if hints.get("tile_takeover_like"): pick["adtypes"].append("Tile_Takeover")
    pick["adtypes"] = sorted(set(pick["adtypes"]))
    return pick

