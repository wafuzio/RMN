def update_taxonomy(slug: str, adtypes: list):
    """Update utils/path_taxonomy.py"""
    taxonomy_path = PROJECT / "utils/path_taxonomy.py"
    
    if not taxonomy_path.exists():
        print(f"⚠️ {taxonomy_path} not found - skipping taxonomy update")
        return
    
    content = taxonomy_path.read_text()
    
    # Build folder set
    folders = set(ADTYPE_MAP.get(at, at) for at in adtypes)
    folders.add("Main")
    folders.add("runs")
    
    folders_str = ",\n        ".join(f'"{f}"' for f in sorted(folders))
    
    new_entry = f'''    "{slug}": {{
        {folders_str},
    }},'''
    
    # Insert before closing brace
    if f'"{slug}"' not in content:
        content = content.replace(
            "\n}",
            f"\n{new_entry}\n}}"
        )
        taxonomy_path.write_text(content)
        print(f"✅ Updated {taxonomy_path}")
    else:
        print(f"⚠️ {slug} already in taxonomy - skipping")

def update_keyword_input(slug: str):
    """Update keyword_input.py to import adapter"""
    keyword_input_path = PROJECT / "keyword_input.py"
    
    if not keyword_input_path.exists():
        print(f"⚠️ {keyword_input_path} not found - skipping")
        return
    
    content = keyword_input_path.read_text()
    import_line = f"import retailers.{slug}.adapter  # noqa: F401"
    
    if import_line not in content:
        # Find the adapter imports section
        if "import retailers." in content:
            lines = content.split("\n")
            for i, line in enumerate(lines):
                if "import retailers." in line and "# noqa: F401" in line:
                    lines.insert(i + 1, import_line)
                    break
            content = "\n".join(lines)
            keyword_input_path.write_text(content)
            print(f"✅ Updated {keyword_input_path}")
        else:
            print(f"⚠️ Could not find adapter import section in {keyword_input_path}")
    else:
        print(f"⚠️ {slug} adapter already imported - skipping")

